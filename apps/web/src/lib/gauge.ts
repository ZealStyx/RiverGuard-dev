/**
 * A local rain-gauge file, and how it overrides the provider's history.
 *
 * Open-Meteo's "past days" are reanalysis — a model's reconstruction, not a
 * measurement — so `rain_today` and the antecedent sums are only as good as that
 * reconstruction. When an operator has real gauge totals (PAGASA Science Garden,
 * a city DRRMO log, an EFCOS feed exported to CSV) they belong in the model
 * input, and the days they cover should replace the provider's estimate one for
 * one rather than being averaged with it.
 *
 * Format — one row per city per day, header required:
 *
 *     date,location,rainfall_mm
 *     2026-11-17,Marikina,18.4
 *     2026-11-17,marikina,18.4        # code or name, either case
 *
 * The file is never generated by this repository: no gauge data is shipped, and
 * an absent file simply means "use the provider". A file that cannot be parsed
 * is reported, not silently ignored.
 *
 * Server-only: `node:fs` is used here and nowhere in the client bundle.
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

import type { DailyWeatherPoint } from "./weather/types";

/** Refuse anything large enough to be a mistake rather than a gauge log. */
const MAX_FILE_BYTES = 2 * 1024 * 1024;
const MAX_RAIN_MM = 1000;

export interface GaugeRainfall {
  /** `YYYY-MM-DD` → millimetres, for the requested location only. */
  readings: Map<string, number>;
  /** Absolute path that was read, whether or not it existed. */
  file: string;
  /** Set when the file exists but could not be used. */
  error: string | null;
}

export interface GaugeStatus {
  configured: boolean;
  file: string;
  /** Rows for any location; 0 when the file is absent. */
  rows: number;
  error: string | null;
}

function repoRoot(): string {
  const cwd = process.cwd();
  return path.basename(cwd) === "web" &&
    path.basename(path.dirname(cwd)) === "apps"
    ? path.resolve(cwd, "..", "..")
    : cwd;
}

export function gaugePath(): string {
  const override = process.env.GAUGE_CSV_PATH?.trim();
  if (override) return path.resolve(override);
  return path.join(repoRoot(), "data", "gauge", "daily_rainfall.csv");
}

function normaliseHeader(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[\s-]+/g, "_");
}

function columnIndex(header: string[], names: string[]): number {
  for (const name of names) {
    const index = header.indexOf(name);
    if (index !== -1) return index;
  }
  return -1;
}

function isIsoDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const parsed = Date.parse(`${value}T00:00:00Z`);
  return Number.isFinite(parsed);
}

interface ParsedGauge {
  /** Rows keyed by `${date}|${normalised location}`. */
  rows: Map<string, number>;
  locationTokens: Map<string, string[]>;
  errors: string[];
}

/**
 * Tolerant CSV reader: header aliases, either case, and a location matched by
 * code or display name. Invalid rows are counted and reported rather than
 * guessed at.
 */
function parseGaugeCsv(text: string): ParsedGauge {
  const rows = new Map<string, number>();
  const locationTokens = new Map<string, string[]>();
  const errors: string[] = [];
  const lines = text.split(/\r?\n/).filter((line) => line.trim().length > 0);
  if (lines.length === 0) {
    return { rows, locationTokens, errors: ["The gauge file is empty."] };
  }

  const header = lines[0].split(",").map(normaliseHeader);
  const dateIndex = columnIndex(header, ["date", "day", "observed_date"]);
  const rainIndex = columnIndex(header, [
    "rainfall_mm",
    "rain_mm",
    "rainfall",
    "rain",
    "precipitation_mm",
    "precipitation",
  ]);
  const locationIndex = columnIndex(header, [
    "location",
    "location_code",
    "locationcode",
    "city",
    "station",
  ]);

  if (dateIndex === -1 || rainIndex === -1 || locationIndex === -1) {
    return {
      rows,
      locationTokens,
      errors: ["The gauge file needs date, location and rainfall_mm columns."],
    };
  }

  let skipped = 0;
  for (const line of lines.slice(1)) {
    const cells = line
      .split(",")
      .map((cell) => cell.trim().replace(/^"|"$/g, ""));
    const date = cells[dateIndex] ?? "";
    const location = (cells[locationIndex] ?? "").toLowerCase();
    const rain = Number(cells[rainIndex]);

    if (!isIsoDate(date) || !location || !Number.isFinite(rain)) {
      skipped += 1;
      continue;
    }
    if (rain < 0 || rain > MAX_RAIN_MM) {
      skipped += 1;
      continue;
    }

    const key = `${date}|${location}`;
    rows.set(key, rain);
    const tokens = locationTokens.get(location) ?? [];
    tokens.push(date);
    locationTokens.set(location, tokens);
  }

  if (skipped > 0) {
    errors.push(
      `${skipped} row${skipped === 1 ? "" : "s"} could not be read (expected YYYY-MM-DD, a location, and 0–${MAX_RAIN_MM} mm).`,
    );
  }
  return { rows, locationTokens, errors };
}

type GaugeFileRead =
  | { kind: "ok"; text: string }
  | { kind: "missing" }
  | { kind: "error"; message: string };

async function readFileSafely(): Promise<GaugeFileRead> {
  try {
    const text = await readFile(gaugePath(), "utf8");
    if (text.length > MAX_FILE_BYTES) {
      return {
        kind: "error",
        message: `The gauge file is larger than ${MAX_FILE_BYTES / 1024 / 1024} MB.`,
      };
    }
    return { kind: "ok", text };
  } catch (error) {
    const code =
      typeof error === "object" && error !== null && "code" in error
        ? (error as { code?: string }).code
        : undefined;
    if (code === "ENOENT") return { kind: "missing" };
    return {
      kind: "error",
      message: `The gauge file could not be read: ${
        error instanceof Error ? error.message : "unknown error"
      }`,
    };
  }
}

/** Rows for one location, keyed by date. Missing file is not an error. */
export async function readGaugeRainfall(location: {
  code: string;
  name: string;
}): Promise<GaugeRainfall> {
  const file = gaugePath();
  const read = await readFileSafely();
  if (read.kind === "missing")
    return { readings: new Map(), file, error: null };
  if (read.kind === "error") {
    return { readings: new Map(), file, error: read.message };
  }

  const parsed = parseGaugeCsv(read.text);
  const wanted = [location.code.toLowerCase(), location.name.toLowerCase()];
  const readings = new Map<string, number>();

  for (const token of wanted) {
    for (const [date, rain] of parsed.rows) {
      const [rowDate, rowLocation] = date.split("|");
      if (rowLocation === token) readings.set(rowDate, rain);
    }
  }

  // Unreadable rows only matter when the file claims to cover this location.
  const touchesLocation = wanted.some((token) =>
    parsed.locationTokens.has(token),
  );
  return {
    readings,
    file,
    error: touchesLocation ? (parsed.errors[0] ?? null) : null,
  };
}

/** For the status panel: whether a gauge file is present and how big it is. */
export async function gaugeStatus(): Promise<GaugeStatus> {
  const file = gaugePath();
  const read = await readFileSafely();
  if (read.kind === "missing") {
    return { configured: false, file, rows: 0, error: null };
  }
  if (read.kind === "error") {
    return { configured: false, file, rows: 0, error: read.message };
  }
  const parsed = parseGaugeCsv(read.text);
  let rows = 0;
  for (const dates of parsed.locationTokens.values()) rows += dates.length;
  return {
    configured: rows > 0,
    file,
    rows,
    error: parsed.errors[0] ?? null,
  };
}

export interface GaugeBlend {
  history: DailyWeatherPoint[];
  gaugeDays: number;
  todayFromGauge: boolean;
}

/**
 * Replace provider rainfall with gauge rainfall, day by day.
 *
 * Days the gauge file does not cover keep the provider's value. The count is
 * reported so the input summary can say "18 of 31 days from a gauge" instead of
 * implying the whole window is measured.
 */
export function blendGaugeRainfall(
  history: DailyWeatherPoint[],
  readings: Map<string, number>,
): GaugeBlend {
  if (readings.size === 0) {
    return { history, gaugeDays: 0, todayFromGauge: false };
  }

  let gaugeDays = 0;
  const blended = history.map((day) => {
    const gauge = readings.get(day.date);
    if (gauge === undefined) return day;
    gaugeDays += 1;
    return { ...day, rainfallMm: Math.round(gauge * 10) / 10 };
  });

  const last = history[history.length - 1];
  const todayFromGauge = Boolean(last && readings.has(last.date));
  return { history: blended, gaugeDays, todayFromGauge };
}
